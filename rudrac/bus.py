"""Shared-bus master, generated from the same .rudra files as the nodes."""
from __future__ import annotations

from typing import List

from .check import Checked
from .link import BB_CODES, protocol_hash
from .util import VERSION


def check_bus(cks: List[Checked]) -> List[str]:
    """Problems that would break a shared wire. Empty list = fine."""
    errs = []
    seen = {}
    for ck in cks:
        n = ck.node
        if n.address is None:
            errs.append(f"node '{n.name}' has no 'address'; every node on a bus needs one (e.g.  address 3)")
            continue
        if n.address in seen:
            errs.append(f"nodes '{seen[n.address]}' and '{n.name}' both use address {n.address}")
        seen[n.address] = n.name
    bauds = {ck.node.baud for ck in cks}
    if len(bauds) > 1:
        errs.append("all nodes on one bus must use the same baud rate, found: " + ", ".join(str(b) for b in sorted(bauds)))
    names = [ck.node.name for ck in cks]
    for nm in set(names):
        if names.count(nm) > 1:
            errs.append(f"node name '{nm}' is used twice")
    return errs


def gen_bus_python(cks: List[Checked]) -> str:
    L = [f'"""Master for a shared bus. Generated by rudrac {VERSION} -- do not edit by hand.',
         "",
         "port: any object with write(bytes) and readline() -> bytes (e.g. pyserial opened with timeout=0.2).",
         "Nodes only speak when asked, and nobody answers a broadcast, so replies never collide.",
         '"""',
         "",
         f"BAUD = {cks[0].node.baud}",
         f"BLACKBOX_CODES = {BB_CODES!r}",
         "",
         "NODES = {"]
    for ck in cks:
        n = ck.node
        hb = next((e.ms for e in n.events if e.kind == "heartbeat" and not e.off), None)
        L.append(f"    {n.name!r}: {{'address': {n.address}, 'proto_hash': {protocol_hash(ck)}, 'heartbeat_ms': {hb}, "
                 f"'commands': {{{', '.join(f'{c!r}: {len(p)}' for c, p in ck.commands)}}}, "
                 f"'states': {ck.states!r}, 'blackbox': {n.blackbox_pos is not None}}},")
    L += ["}",
          "BY_ADDRESS = {v['address']: k for k, v in NODES.items()}",
          "",
          "",
          "class Bus:",
          "    def __init__(self, port):",
          "        self.port = port",
          "",
          "    def _line(self, text):",
          '        self.port.write((text + "\\n").encode("ascii"))',
          "",
          "    def send(self, node, command, *args):",
          '        """Send  @<address> COMMAND args  to one node (by name). Arguments are checked against the protocol."""',
          "        spec = NODES[node]",
          '        builtin = {"PING": 0, "WHO": 0, "STATUS": 0, "STATE": 0, "LOG": 0}',
          '        want = spec["commands"].get(command, builtin.get(command))',
          "        if want is None:",
          '            raise KeyError(f"node {node} has no command {command}")',
          "        if len(args) != want:",
          '            raise TypeError(f"{command} takes {want} argument(s)")',
          '        self._line(" ".join([f"@{spec[\'address\']}", command] + [str(int(a)) for a in args]))',
          "",
          "    def broadcast(self, command, *args):",
          '        """Send to every node at once (@0). Nobody answers. Use for PING keep-alives and emergency stops."""',
          '        self._line(" ".join(["@0", command] + [str(int(a)) for a in args]))',
          "",
          "    def read(self):",
          '        """One reply as (node_name, message, [ints]), or None on timeout / unknown sender."""',
          "        raw = self.port.readline()",
          "        if not raw:",
          "            return None",
          '        parts = raw.decode("ascii", "replace").strip().split()',
          '        if len(parts) < 2 or not parts[0].startswith("@"):',
          "            return None",
          "        try:",
          "            addr = int(parts[0][1:])",
          "        except ValueError:",
          "            return None",
          "        vals = []",
          "        for tok in parts[2:]:",
          "            try:",
          "                vals.append(int(tok))",
          "            except ValueError:",
          "                break",
          "        name = BY_ADDRESS.get(addr)",
          "        return (name, parts[1], vals) if name else None",
          "",
          "    def ask(self, node, command, *args, tries=8):",
          '        """Send, then return the first reply that comes from that node."""',
          "        self.send(node, command, *args)",
          "        for _ in range(tries):",
          "            r = self.read()",
          "            if r and r[0] == node:",
          "                return r",
          "        return None",
          "",
          "    def verify_all(self):",
          '        """{node: True/False}: does each node report the fingerprint this master was generated for?"""',
          "        out = {}",
          "        for name, spec in NODES.items():",
          '            r = self.ask(name, "WHO")',
          '            out[name] = bool(r and r[1] == "WHO" and r[2] and r[2][0] == spec["proto_hash"])',
          "        return out",
          "",
          "    def black_box(self, node, tries=90):",
          '        """Read a node\'s black box: list of (time_ms, what, argument), oldest first."""',
          '        self.send(node, "LOG")',
          "        out = []",
          "        for _ in range(tries):",
          "            r = self.read()",
          "            if not r or r[0] != node:",
          "                continue",
          '            if r[1] == "LOGEND":',
          "                return out",
          '            if r[1] == "LOG" and len(r[2]) == 3:',
          "                out.append((r[2][0], BLACKBOX_CODES.get(r[2][1], str(r[2][1])), r[2][2]))",
          "        return out",
          ""]
    return "\n".join(L)


def gen_bus_doc(cks: List[Checked]) -> str:
    L = ["# Shared bus", "", f"Generated by rudrac {VERSION}. Do not edit by hand.", "",
         f"* Serial, **{cks[0].node.baud} baud**, one text line per message, shared by every node (RS485 or similar).",
         "* A line to a node starts with its address: `@3 PING`. `@0` = broadcast: all nodes obey, **nobody answers**.",
         "* A node answers only when asked, and its reply starts with its own address: `@3 PONG`.",
         "* Every node keeps its own heartbeat: a line addressed to it, or a broadcast, resets it.",
         "", "| Node | Address | Board | Commands |", "|---|---|---|---|"]
    for ck in sorted(cks, key=lambda c: c.node.address):
        n = ck.node
        cmds = ", ".join(f"`{c}{'(' + ', '.join(p) + ')' if p else ''}`" for c, p in ck.commands) or "-"
        L.append(f"| {n.name} | {n.address} | {n.target} | {cmds} |")
    L.append("")
    return "\n".join(L)
