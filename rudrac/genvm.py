"""C++ side of the bytecode VM: interpreter, firmware tables and the IMG commands. Used by `gen.generate(vm=True)`."""
from __future__ import annotations

from typing import List

from . import bytecode as B
from .util import ANIM_MODES


def caps(img: B.Image, slack: int) -> dict:
    """Capacities the firmware is built with: what the factory image needs plus some room for updates."""
    return {"cap": len(img.encode()) + slack, "stack": img.stack + 16, "frame": img.frame + 16, "calls": img.calls + 2}


def cn(slot: str) -> str:
    return "v_" + slot.replace(".", "__")


def emit(ck, w, img: B.Image, slack: int, bb: bool, has_states: bool, start_handlers: List[int]):
    tb = B.tables(ck)
    cp = caps(img, slack)
    data = img.encode()
    nh, nf = len(img.handlers), len(img.fns)
    w("// ---- bytecode VM: handler and function bodies live in an image that can be replaced over the serial link ----")
    w("#define VM_UNUSED __attribute__((unused))")
    w(f"#define VM_CAP {cp['cap']}")
    w(f"#define VM_STACK {cp['stack']}")
    w(f"#define VM_FRAME {cp['frame']}")
    w(f"#define VM_CALLS {cp['calls']}")
    w(f"#define VM_NH {nh}")
    w(f"#define VM_NF {nf}")
    w(f"#define VM_SHAPE {img.shape}UL")
    w("#ifdef __AVR__")
    w("#define VM_PROGMEM PROGMEM")
    w("#define VM_COPY(d, s, n) memcpy_P((d), (s), (n))")
    w("#else")
    w("#define VM_PROGMEM")
    w("#define VM_COPY(d, s, n) memcpy((d), (s), (n))")
    w("#endif")
    rows = [", ".join(f"0x{b:02x}" for b in data[k:k + 16]) for k in range(0, len(data), 16)]
    w(f"static const uint8_t vm_factory[{len(data)}] VM_PROGMEM = {{")
    for r in rows:
        w("  " + r + ",")
    w("};")
    w("static uint8_t vm_img[VM_CAP];")
    w("static uint16_t vm_len = 0;        /* bytes of the running image; 0 while an update is in progress */")
    w("static bool vm_valid = false;")
    w("static rt_int vm_stk[VM_STACK];")
    w("static rt_int vm_loc[VM_FRAME];")
    sizes = ", ".join(str(s[2]) for s in tb.slots) or "0"
    w(f"static const uint16_t vm_size[] = {{{sizes}}};")
    w("")

    # ---- slot access
    w("static VM_UNUSED rt_int vm_gget(uint8_t s, rt_int i) {")
    w("  (void)i;")
    w("  switch (s) {")
    for k, (name, ty, size) in enumerate(tb.slots):
        w(f"    case {k}: return (rt_int){cn(name)}{'[i]' if size else ''};")
    w("    default: return 0;")
    w("  }")
    w("}")
    w("static VM_UNUSED void vm_gset(uint8_t s, rt_int i, rt_int v) {")
    w("  (void)i; (void)v;")
    w("  switch (s) {")
    for k, (name, ty, size) in enumerate(tb.slots):
        val = "(v != 0)" if ty == "bool" else "v"
        w(f"    case {k}: {cn(name)}{'[i]' if size else ''} = {val}; break;")
    w("    default: break;")
    w("  }")
    w("}")
    # ---- io
    w("static VM_UNUSED rt_int vm_in(uint8_t k) {")
    w("  switch (k) {")
    for k, n in enumerate(tb.ins):
        w(f"    case {k}: return (rt_int)i_{n}();")
    w("    default: return 0;")
    w("  }")
    w("}")
    w("static VM_UNUSED rt_int vm_outr(uint8_t k) {")
    w("  switch (k) {")
    for k, n in enumerate(tb.outs):
        w(f"    case {k}: return (rt_int)o_{n};")
    w("    default: return 0;")
    w("  }")
    w("}")
    ios = {d.name: d for d in ck.node.decls if d.__class__.__name__ == "IO"}
    w("static VM_UNUSED void vm_seto(uint8_t k, rt_int v) {")
    w("  (void)v;")
    w("  switch (k) {")
    for k, n in enumerate(tb.outs):
        arg = "(v != 0)" if ios[n].kind == "digital" else "v"
        w(f"    case {k}: r_set_{n}({arg}); break;")
    w("    default: break;")
    w("  }")
    w("}")
    if tb.paths:
        w("static VM_UNUSED void vm_runp(uint8_t k) {")
        w("  switch (k) {")
        for k, n in enumerate(tb.paths):
            w(f"    case {k}: path_run_{n}(); break;")
        w("    default: break;")
        w("  }")
        w("}")
        w("static VM_UNUSED rt_int vm_prun(uint8_t k) {")
        w("  switch (k) {")
        for k, n in enumerate(tb.paths):
            w(f"    case {k}: return pst_{n} != 0;")
        w("    default: return 0;")
        w("  }")
        w("}")
        pouts = sorted({p.out for p in ck.node.paths})
        for fn in ("stop", "cancel"):
            w(f"static VM_UNUSED void vm_{fn}o(uint8_t k) {{")
            w("  switch (k) {")
            for n in pouts:
                w(f"    case {tb.outs.index(n)}: path_{fn}_{n}(); break;")
            w("    default: break;")
            w("  }")
            w("}")
    w("static VM_UNUSED void vm_send(uint8_t m, rt_int v, bool has) {")
    w("  (void)v; (void)has;")
    w("  switch (m) {")
    for k, m in enumerate(tb.messages):
        if ck.messages[m]:
            w(f'    case {k}: tx_begin(); TX_STR("{m} "); TX_NUM((long)v); tx_end(); break;')
        else:
            w(f'    case {k}: tx_begin(); TX_STR("{m}"); tx_end(); break;')
    w("    default: break;")
    w("  }")
    w("}")
    w("static VM_UNUSED void vm_strip(uint8_t op, uint8_t s, uint8_t mode, const rt_int *a) {")
    w("  (void)op; (void)mode; (void)a;")
    w("  switch (s) {")
    for k, n in enumerate(tb.strips):
        w(f"    case {k}:")
        w(f"      if (op == {B.FILL}) r_fill_{n}(a[0], a[1], a[2]);")
        w(f"      else if (op == {B.PIXEL}) r_pixel_{n}(a[0], a[1], a[2], a[3]);")
        if ck.uses_anim:
            w(f"      else if (mode == 255) r_anim_off_{n}();")
            w(f"      else if (mode == {ANIM_MODES['rainbow']}) r_animate_{n}(mode, 0, 0, 0, a[0]);")
            w(f"      else r_animate_{n}(mode, a[0], a[1], a[2], a[3]);")
        w("      break;")
    w("    default: break;")
    w("  }")
    w("}")
    w("static VM_UNUSED void vm_bad_index(rt_int i) {")
    w("  (void)i;")
    w("  g_blocked++;" + (" bb_log(6, i);" if bb else ""))
    w("}")
    w("")

    # ---- interpreter
    w("static void vm_run(uint8_t h, const rt_int *args, uint8_t na) {")
    w("  if (!vm_valid) return;")
    w("  const uint8_t *tab = vm_img + 13;")
    w("  const uint8_t *code = tab + 4 * (VM_NH + VM_NF) + 2;")
    w("  uint16_t rpc[VM_CALLS], rlb[VM_CALLS], rnl[VM_CALLS];")
    w("  uint8_t depth = 0;")
    w("  uint16_t sp = 0, lb = 0, nl = tab[4 * h + 3], pc = (uint16_t)(tab[4 * h] | (tab[4 * h + 1] << 8));")
    w("  uint8_t np = tab[4 * h + 2];")
    w("  if (nl > VM_FRAME) goto fault;")
    w("  for (uint16_t k = 0; k < nl; k++) vm_loc[k] = (k < np && k < na) ? args[k] : 0;")
    w("  for (;;) {")
    w("    uint8_t op = code[pc++];")
    w("    switch (op) {")
    w("#define NEED(n) do { if (sp < (n)) goto fault; } while (0)")
    w("#define ROOM() do { if (sp >= VM_STACK) goto fault; } while (0)")
    w("#define U16(at) ((uint16_t)(code[at] | (code[(at) + 1] << 8)))")
    w(f"      case {B.PUSH8}: ROOM(); vm_stk[sp++] = (int8_t)code[pc]; pc += 1; break;")
    w(f"      case {B.PUSH32}: ROOM(); vm_stk[sp++] = (rt_int)((uint32_t)code[pc] | ((uint32_t)code[pc + 1] << 8) | ((uint32_t)code[pc + 2] << 16) | ((uint32_t)code[pc + 3] << 24)); pc += 4; break;")
    w(f"      case {B.LOADL}: ROOM(); vm_stk[sp++] = vm_loc[lb + code[pc]]; pc += 1; break;")
    w(f"      case {B.STOREL}: NEED(1); vm_loc[lb + code[pc]] = vm_stk[--sp]; pc += 1; break;")
    w(f"      case {B.LOADG}: ROOM(); vm_stk[sp++] = vm_gget(code[pc], 0); pc += 1; break;")
    w(f"      case {B.STOREG}: NEED(1); vm_gset(code[pc], 0, vm_stk[--sp]); pc += 1; break;")
    w(f"      case {B.LOADE}: {{ NEED(1); rt_int i = vm_stk[sp - 1]; uint8_t s = code[pc]; pc += 1;")
    w("        vm_stk[sp - 1] = (i >= 0 && i < (rt_int)vm_size[s]) ? vm_gget(s, i) : 0; break; }")
    w(f"      case {B.STOREE}: {{ NEED(2); rt_int v = vm_stk[--sp]; rt_int i = vm_stk[--sp]; uint8_t s = code[pc]; pc += 1;")
    w("        if (i >= 0 && i < (rt_int)vm_size[s]) vm_gset(s, i, v); else vm_bad_index(i); break; }")
    w(f"      case {B.IN}: ROOM(); vm_stk[sp++] = vm_in(code[pc]); pc += 1; break;")
    w(f"      case {B.OUTR}: ROOM(); vm_stk[sp++] = vm_outr(code[pc]); pc += 1; break;")
    w(f"      case {B.SETO}: NEED(1); vm_seto(code[pc], vm_stk[--sp]); pc += 1; break;")
    for op, fn in ((B.ADD, "rt_add"), (B.SUB, "rt_sub"), (B.MUL, "rt_mul"), (B.DIV, "rt_div"), (B.MOD, "rt_mod")):
        w(f"      case {op}: NEED(2); sp--; vm_stk[sp - 1] = {fn}(vm_stk[sp - 1], vm_stk[sp]); break;")
    w(f"      case {B.NEG}: NEED(1); vm_stk[sp - 1] = rt_neg(vm_stk[sp - 1]); break;")
    w(f"      case {B.NOT}: NEED(1); vm_stk[sp - 1] = vm_stk[sp - 1] ? 0 : 1; break;")
    for op, c in ((B.LT, "<"), (B.LE, "<="), (B.GT, ">"), (B.GE, ">="), (B.EQ, "=="), (B.NE, "!=")):
        w(f"      case {op}: NEED(2); sp--; vm_stk[sp - 1] = (vm_stk[sp - 1] {c} vm_stk[sp]) ? 1 : 0; break;")
    w(f"      case {B.JMP}: pc = U16(pc); break;")
    w(f"      case {B.JZ}: NEED(1); if (!vm_stk[--sp]) pc = U16(pc); else pc += 2; break;")
    w(f"      case {B.JZK}: NEED(1); if (!vm_stk[sp - 1]) pc = U16(pc); else {{ sp--; pc += 2; }} break;")
    w(f"      case {B.JNZK}: NEED(1); if (vm_stk[sp - 1]) pc = U16(pc); else {{ sp--; pc += 2; }} break;")
    w(f"      case {B.CALL}: {{")
    w("        uint8_t u = (uint8_t)(VM_NH + code[pc]); pc += 2;")
    w("        uint8_t n = tab[4 * u + 2]; uint16_t nl2 = tab[4 * u + 3];")
    w("        if (depth + 1 >= VM_CALLS || sp < n || (uint32_t)lb + nl + nl2 > VM_FRAME) goto fault;")
    w("        rpc[depth] = pc; rlb[depth] = lb; rnl[depth] = nl; depth++;")
    w("        lb = (uint16_t)(lb + nl); nl = nl2; sp = (uint16_t)(sp - n);")
    w("        for (uint16_t k = 0; k < nl; k++) vm_loc[lb + k] = (k < n) ? vm_stk[sp + k] : 0;")
    w("        pc = (uint16_t)(tab[4 * u] | (tab[4 * u + 1] << 8));")
    w("        break; }")
    w(f"      case {B.RET}: {{ NEED(1); rt_int v = vm_stk[--sp];")
    w("        if (!depth) return;")
    w("        depth--; pc = rpc[depth]; lb = rlb[depth]; nl = rnl[depth]; vm_stk[sp++] = v; break; }")
    w(f"      case {B.RETV}:")
    w("        if (!depth) return;")
    w("        depth--; pc = rpc[depth]; lb = rlb[depth]; nl = rnl[depth]; break;")
    w(f"      case {B.POP}: NEED(1); sp--; break;")
    if tb.paths:
        w(f"      case {B.RUNP}: vm_runp(code[pc]); pc += 1; break;")
        w(f"      case {B.STOPO}: vm_stopo(code[pc]); pc += 1; break;")
        w(f"      case {B.CANCEL}: vm_cancelo(code[pc]); pc += 1; break;")
        w(f"      case {B.PRUN}: ROOM(); vm_stk[sp++] = vm_prun(code[pc]); pc += 1; break;")
    if has_states:
        w(f"      case {B.GOTO}: r_goto(code[pc]); pc += 1; break;")
    w(f"      case {B.SEND}: NEED(1); vm_send(code[pc], vm_stk[--sp], true); pc += 1; break;")
    w(f"      case {B.SENDN}: vm_send(code[pc], 0, false); pc += 1; break;")
    if tb.strips:
        w(f"      case {B.FILL}: NEED(3); sp -= 3; vm_strip({B.FILL}, code[pc], 0, vm_stk + sp); pc += 1; break;")
        w(f"      case {B.PIXEL}: NEED(4); sp -= 4; vm_strip({B.PIXEL}, code[pc], 0, vm_stk + sp); pc += 1; break;")
        w(f"      case {B.ANIM}: {{ uint8_t s = code[pc], mode = code[pc + 1]; pc += 2;")
        w(f"        uint8_t n = (mode == {ANIM_MODES['rainbow']}) ? 1 : (mode == 255 ? 0 : 4);")
        w("        NEED(n); sp -= n; vm_strip(" + str(B.ANIM) + ", s, mode, vm_stk + sp); break; }")
    w("      default: goto fault;")
    w("    }")
    w("  }")
    w("fault:   /* cannot happen with an image rudrac produced; stop running images if it does */")
    w("  vm_valid = false;")
    w("  r_apply_safe();")
    w("}")
    w("")

    # ---- image management
    w("static VM_UNUSED uint32_t vm_fnv(const uint8_t *b, uint16_t n) {")
    w("  uint32_t h = 0x811C9DC5UL;")
    w("  while (n--) { h ^= *b++; h *= 0x01000193UL; }")
    w("  return h & 0x7FFFFFFFUL;")
    w("}")
    w("static bool vm_accept(uint16_t n, uint32_t check) {")
    w("  const uint8_t *b = vm_img;")
    w("  if (n < 18 || n > VM_CAP) return false;")
    w("  if (b[0] != 'R' || b[1] != 'B' || b[2] != 1) return false;")
    w("  uint32_t tr = (uint32_t)b[n - 4] | ((uint32_t)b[n - 3] << 8) | ((uint32_t)b[n - 2] << 16) | ((uint32_t)b[n - 1] << 24);")
    w("  uint32_t h = vm_fnv(b, (uint16_t)(n - 4));")
    w("  if (h != tr || h != check) return false;")
    w("  uint32_t shape = (uint32_t)b[3] | ((uint32_t)b[4] << 8) | ((uint32_t)b[5] << 16) | ((uint32_t)b[6] << 24);")
    w("  if (shape != VM_SHAPE || b[7] != VM_NH || b[8] != VM_NF) return false;")
    w("  if (b[9] > VM_STACK || (uint16_t)(b[10] | (b[11] << 8)) > VM_FRAME || b[12] > VM_CALLS) return false;")
    w("  uint16_t p = (uint16_t)(13 + 4 * (VM_NH + VM_NF));")
    w("  if ((uint32_t)p + 2 + 4 > n) return false;")
    w("  uint16_t cl = (uint16_t)(b[p] | (b[p + 1] << 8));")
    w("  if ((uint32_t)p + 2 + cl + 4 != n) return false;")
    w("  for (uint8_t k = 0; k < VM_NH + VM_NF; k++) {")
    w("    uint16_t off = (uint16_t)(b[13 + 4 * k] | (b[14 + 4 * k] << 8));")
    w("    if (off >= cl) return false;")
    w("  }")
    w("  return true;")
    w("}")
    w("static void vm_start(void);")
    w("static void vm_cmd_img(char *p) {")
    w("  char *e = NULL;")
    w("  long off = strtol(p, &e, 10);")
    w("  if (e == p || off < 0) { tx_begin(); TX_STR(\"ERR\"); tx_end(); return; }")
    w("  p = e;")
    w("  while (*p == ' ') p++;")
    w("  uint8_t buf[16]; uint8_t n = 0;")
    w("  while (*p && *p != ' ') {")
    w("    int hi = (*p >= '0' && *p <= '9') ? *p - '0' : (*p >= 'a' && *p <= 'f') ? *p - 'a' + 10 : (*p >= 'A' && *p <= 'F') ? *p - 'A' + 10 : -1;")
    w("    int lo = (hi >= 0 && p[1]) ? ((p[1] >= '0' && p[1] <= '9') ? p[1] - '0' : (p[1] >= 'a' && p[1] <= 'f') ? p[1] - 'a' + 10 : (p[1] >= 'A' && p[1] <= 'F') ? p[1] - 'A' + 10 : -1) : -1;")
    w("    if (hi < 0 || lo < 0 || n >= sizeof(buf)) { tx_begin(); TX_STR(\"ERR\"); tx_end(); return; }")
    w("    buf[n++] = (uint8_t)(hi * 16 + lo);")
    w("    p += 2;")
    w("  }")
    w("  if (!n || off + n > VM_CAP) { tx_begin(); TX_STR(\"ERR\"); tx_end(); return; }")
    w("  if (vm_valid) { vm_valid = false; vm_len = 0; r_apply_safe(); }   /* node goes safe while it is being reprogrammed */")
    w("  memcpy(vm_img + off, buf, n);")
    w("  tx_begin(); TX_STR(\"OK\"); tx_end();")
    w("}")
    w("static void vm_cmd_end(char *p) {")
    w("  char *e = NULL;")
    w("  long n = strtol(p, &e, 10);")
    w("  if (e == p) { tx_begin(); TX_STR(\"ERR\"); tx_end(); return; }")
    w("  p = e;")
    w("  char *e2 = NULL;")
    w("  long chk = strtol(p, &e2, 10);")
    w("  if (e2 == p || n < 0 || n > VM_CAP || !vm_accept((uint16_t)n, (uint32_t)chk)) { tx_begin(); TX_STR(\"ERR\"); tx_end(); return; }")
    w("  vm_len = (uint16_t)n; vm_valid = true;")
    w("  tx_begin(); TX_STR(\"IMGOK\"); tx_end();")
    w("  vm_start();")
    w("}")
    w("static void vm_cmd_reset(void) {")
    w("  VM_COPY(vm_img, vm_factory, sizeof(vm_factory));")
    w("  vm_len = sizeof(vm_factory); vm_valid = true;")
    w("  tx_begin(); TX_STR(\"IMGOK\"); tx_end();")
    w("  vm_start();")
    w("}")
    w("static void vm_cmd_info(void) {")
    w('  tx_begin(); TX_STR("IMGINFO "); TX_NUM(VM_CAP); TX_STR(" "); TX_NUM(vm_len); TX_STR(" "); TX_NUM(vm_valid ? 1 : 0); tx_end();')
    w("}")
    w("")
